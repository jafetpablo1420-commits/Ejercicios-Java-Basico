    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        
        // Obliga a la tabla a guardar el texto que se esté editando en ese instante
        if (jTable1.isEditing()) {
            jTable1.getCellEditor().stopCellEditing();
        }
        
        int fila = jTable1.getSelectedRow();
    if (fila >= 0) {
        try {
            Connection con = Conexion.Conect();
            String sql = "UPDATE farmacos SET Nombre_generico=?, Nombre_comercial=?, Stock=?, Precio=? WHERE idfarmacos=?";
            PreparedStatement ps = con.prepareStatement(sql);
            
            // Aquí jTable1.getValueAt(fila, columna) obtiene el texto editado directamente de la celda
            ps.setString(1, jTable1.getValueAt(fila, 1).toString());
            ps.setString(2, jTable1.getValueAt(fila, 2).toString());
            ps.setString(3, jTable1.getValueAt(fila, 5).toString());
            ps.setString(4, jTable1.getValueAt(fila, 7).toString());
            ps.setInt(5, Integer.parseInt(jTable1.getValueAt(fila, 0).toString()));
            
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Medicamento actualizado correctamente");
            cargarMedicamentos(); // Recargas la tabla para ver los cambios
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
        }
    } else {
        JOptionPane.showMessageDialog(this, "Por favor, selecciona una fila de la tabla primero");
    }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int fila = jTable1.getSelectedRow();
    if (fila >= 0) {
        int confirmar = JOptionPane.showConfirmDialog(this, "¿Estás seguro de eliminar este medicamento?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (confirmar == JOptionPane.YES_OPTION) {
            try {
                Connection con = Conexion.Conect();
                String sql = "DELETE FROM farmacos WHERE idfarmacos=?";
                PreparedStatement ps = con.prepareStatement(sql);
                
                // Obtiene el ID de la fila seleccionada (columna 0)
                ps.setInt(1, Integer.parseInt(jTable1.getValueAt(fila, 0).toString()));
                
                ps.executeUpdate();
                JOptionPane.showMessageDialog(this, "Medicamento eliminado correctamente");
                cargarMedicamentos(); // Recarga la tabla limpia
                
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
            }
        }
    } else {
        JOptionPane.showMessageDialog(this, "Por favor, selecciona una fila de la tabla primero");
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

