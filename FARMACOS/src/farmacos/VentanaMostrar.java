    public void cargarMedicamentos() {
        
        // Definimos el modelo sobreescribiendo el método que controla la edición
        DefaultTableModel modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                // El ID (columna 0) no se puede editar, las demás sí (devuelve true)
                return column != 0; 
            }
        };
    
        modelo.addColumn("Id");
        modelo.addColumn("Nombre Generico");
        modelo.addColumn("Nombre Comercial");
        modelo.addColumn("Forma");
        modelo.addColumn("Concentracion");
        modelo.addColumn("Stock");
        modelo.addColumn("Fecha de vencimiento");
        modelo.addColumn("Precio");

        jTable1.setModel(modelo);
    
    // Consulta adaptada a los nombres exactos de tu imagen
    String sql = "SELECT idfarmacos, Nombre_generico, Nombre_comercial, Forma_farmaceutica, Concentracion, Stock, Fecha_vencimiento, Precio FROM farmacos"; 
    
    try {
        Connection con = Conexion.Conect(); 
        Statement st = con.createStatement();
        ResultSet rs = st.executeQuery(sql);
        
        while (rs.next()) {
            Object[] fila = new Object[8]; 
            
            fila[0] = rs.getInt("idfarmacos"); // Cambiado a idfarmacos
            fila[1] = rs.getString("Nombre_generico");
            fila[2] = rs.getString("Nombre_comercial");
            fila[3] = rs.getString("Forma_farmaceutica"); // Cambiado a Forma_farmaceutica
            fila[4] = rs.getString("Concentracion");
            fila[5] = rs.getString("Stock"); // Obtenido como String porque en tu BD es VARCHAR
            fila[6] = rs.getString("Fecha_vencimiento");
            fila[7] = rs.getString("Precio"); // Obtenido como String porque en tu BD es VARCHAR
            
            modelo.addRow(fila);
        }
    } catch (SQLException e) {
        System.out.println("Error al cargar medicamentos: " + e.getMessage());
    }
}

